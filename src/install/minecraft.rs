//! Vanilla pieces: the version file, libraries, client jar, log config and
//! assets (sounds, languages).

use crate::game::version::{FileRef, VersionJson};
use crate::net::{Download, Net};
use crate::paths::Paths;
use anyhow::{Context, Result};
use serde::Deserialize;
use std::collections::HashMap;

const VERSION_MANIFEST_URL: &str =
    "https://piston-meta.mojang.com/mc/game/version_manifest_v2.json";
const ASSETS_URL: &str = "https://resources.download.minecraft.net";

#[derive(Deserialize)]
struct VersionManifest {
    versions: Vec<ManifestVersion>,
}

#[derive(Deserialize)]
struct ManifestVersion {
    id: String,
    url: String,
    sha1: String,
}

#[derive(Deserialize)]
struct AssetIndex {
    objects: HashMap<String, AssetObject>,
}

#[derive(Deserialize)]
struct AssetObject {
    hash: String,
    size: u64,
}

/// Fetches `versions/<mc>/<mc>.json`, which tells us which Java to install.
pub async fn ensure_version_file(net: &Net, paths: &Paths, minecraft: &str) -> Result<()> {
    let path = paths.version_file(minecraft, "json");
    if path.exists() {
        return Ok(());
    }
    let manifest: VersionManifest = net.json(VERSION_MANIFEST_URL).await?;
    let entry = manifest
        .versions
        .into_iter()
        .find(|v| v.id == minecraft)
        .with_context(|| format!("Minecraft {minecraft} not found"))?;
    net.download(&Download {
        url: entry.url,
        path,
        sha1: Some(entry.sha1),
        size: None,
    })
    .await
}

/// Libraries, client jar and log config for the resolved (NeoForge) version.
/// The vanilla client jar is stored as `versions/<id>/<id>.jar`, the name
/// NeoForge's `ignoreList` expects, like the official launcher does.
pub async fn ensure_libraries(
    net: &Net,
    paths: &Paths,
    version: &VersionJson,
    on_progress: impl Fn(usize, usize),
) -> Result<()> {
    let libraries = paths.libraries();
    let mut files: Vec<Download> = version
        .artifacts()
        // Empty URLs are generated by the NeoForge installer, not downloaded.
        .filter(|artifact| !artifact.url.is_empty())
        .map(|artifact| Download {
            url: artifact.url.clone(),
            path: libraries.join(&artifact.path),
            sha1: artifact.sha1.clone(),
            size: artifact.size,
        })
        .collect();

    let client = &version
        .downloads
        .as_ref()
        .context("no client jar in version file")?
        .client;
    let client_jar = paths.version_file(&version.id, "jar");
    files.push(file_download(client, client_jar));

    if let Some(logging) = version
        .logging
        .as_ref()
        .and_then(|logging| logging.client.as_ref())
    {
        let path = paths.assets().join("log_configs").join(&logging.file.id);
        files.push(file_download(&logging.file.file, path));
    }
    net.download_all(&files, on_progress).await
}

/// The asset index and every object it lists.
pub async fn ensure_assets(
    net: &Net,
    paths: &Paths,
    version: &VersionJson,
    on_progress: impl Fn(usize, usize),
) -> Result<()> {
    let index_ref = version
        .asset_index
        .as_ref()
        .context("no asset index in version file")?;
    let index_path = paths
        .assets()
        .join("indexes")
        .join(format!("{}.json", index_ref.id));
    net.download_all(
        &[file_download(&index_ref.file, index_path.clone())],
        |_, _| {},
    )
    .await?;
    let index: AssetIndex = serde_json::from_str(&std::fs::read_to_string(&index_path)?)?;

    let objects = paths.assets().join("objects");
    let mut files: Vec<Download> = index
        .objects
        .into_values()
        .map(|object| {
            let prefix = &object.hash[..2];
            Download {
                url: format!("{ASSETS_URL}/{prefix}/{}", object.hash),
                path: objects.join(prefix).join(&object.hash),
                sha1: Some(object.hash),
                size: Some(object.size),
            }
        })
        .collect();
    files.sort_by(|a, b| a.path.cmp(&b.path));
    files.dedup_by(|a, b| a.path == b.path);
    net.download_all(&files, on_progress).await
}

fn file_download(file: &FileRef, path: std::path::PathBuf) -> Download {
    Download {
        url: file.url.clone(),
        path,
        sha1: Some(file.sha1.clone()),
        size: Some(file.size),
    }
}
